import AppKit
import Observation

/// One copied (or saved) thing: text or an image (spec CB-1).
struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    enum Kind: String, Codable, Sendable {
        case text
        case image
    }

    var id = UUID()
    let kind: Kind
    /// The text, or a short description of an image.
    let text: String
    /// The image's file in the clipboard folder.
    var imageFile: String?
    var date = Date()
}

/// Which list the clipboard shows and pastes from (spec CB-2).
enum ClipboardTab: String, CaseIterable, Sendable {
    case history
    case saved

    var title: String {
        switch self {
        case .history: "Clipboard"
        case .saved: "Saved"
        }
    }
}

enum ClipboardRules {
    /// Copies marked as secret or temporary (password managers) are never kept (spec CB-6).
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "Pasteboard generator type"
    ]

    static func isSkipped(types: [String]) -> Bool {
        !skippedTypes.isDisjoint(with: types)
    }

    /// The newest first, without an older copy of the same text, at most `limit`.
    static func adding(_ item: ClipItem, to items: [ClipItem], limit: Int) -> [ClipItem] {
        var result = items.filter { !(item.kind == .text && $0.kind == .text && $0.text == item.text) }
        result.insert(item, at: 0)
        return Array(result.prefix(max(limit, 1)))
    }
}

/// The clipboard history and the saved items, kept on disk (spec CB-1…CB-7).
@MainActor
@Observable
final class ClipboardStore {
    private(set) var history: [ClipItem] = []
    private(set) var saved: [ClipItem] = []
    /// A copied code the smart opening points at, for 2 minutes (spec SO-5).
    private(set) var highlighted: UUID?
    @ObservationIgnored private var highlightTask: Task<Void, Never>?

    /// How many copies are kept.
    var limit: Int {
        didSet {
            // Typed numbers outside the range are brought back into it.
            guard Self.limitRange.contains(limit) else {
                limit = min(max(limit, Self.limitRange.lowerBound), Self.limitRange.upperBound)
                return
            }
            defaults.set(limit, forKey: Keys.limit)
            history = Array(history.prefix(limit))
            persist()
        }
    }

    /// How long the modifier is held before the items show (spec CB-3b); a shorter press pastes
    /// the newest one.
    var showDelay: Double {
        didSet { defaults.set(showDelay, forKey: Keys.showDelay) }
    }

    static let showDelayRange: ClosedRange<Double> = 0.05...0.5

    var historyShortcut: KeyShortcut? {
        didSet { defaults.set(historyShortcut.flatMap { try? JSONEncoder().encode($0) }, forKey: Keys.historyShortcut) }
    }

    var savedShortcut: KeyShortcut? {
        didSet { defaults.set(savedShortcut.flatMap { try? JSONEncoder().encode($0) }, forKey: Keys.savedShortcut) }
    }

    /// Apps whose copies are not kept (bundle identifiers).
    private(set) var excludedApps: [String] {
        didSet { defaults.set(excludedApps, forKey: Keys.excluded) }
    }

    static let limitRange = 5...100

    private enum Keys {
        static let limit = "clipboardLimit"
        static let historyShortcut = "clipboardShortcut"
        static let savedShortcut = "clipboardSavedShortcut"
        static let excluded = "clipboardExcludedApps"
        static let showDelay = "clipboardShowDelay"
    }

    private let defaults: UserDefaults
    private let folder: URL
    @ObservationIgnored private var lastCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?

    init(defaults: UserDefaults = .standard, folder: URL? = nil) {
        self.defaults = defaults
        showDelay = defaults.object(forKey: Keys.showDelay) as? Double ?? 0.12
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first
            ?? URL(fileURLWithPath: NSTemporaryDirectory())
        self.folder = folder ?? support.appendingPathComponent("Dynotch/Clipboard")
        limit = min(max(defaults.object(forKey: Keys.limit) as? Int ?? 25, Self.limitRange.lowerBound), Self.limitRange.upperBound)
        historyShortcut = Self.shortcut(defaults, Keys.historyShortcut) ?? KeyShortcut.optionV
        savedShortcut = Self.shortcut(defaults, Keys.savedShortcut) ?? KeyShortcut.optionShiftV
        excludedApps = defaults.stringArray(forKey: Keys.excluded) ?? []
        load()
    }

    private static func shortcut(_ defaults: UserDefaults, _ key: String) -> KeyShortcut? {
        defaults.data(forKey: key).flatMap { try? JSONDecoder().decode(KeyShortcut.self, from: $0) }
    }

    func items(in tab: ClipboardTab) -> [ClipItem] {
        tab == .history ? history : saved
    }

    // MARK: - Watching the pasteboard

    /// Outlines the newest history item with this text (polling the copy first, so it is there).
    func highlight(_ text: String) {
        poll()
        let wanted = text.trimmingCharacters(in: .whitespacesAndNewlines)
        highlighted = history.first { $0.kind == .text && $0.text.trimmingCharacters(in: .whitespacesAndNewlines) == wanted }?.id
        highlightTask?.cancel()
        highlightTask = Task { [weak self] in
            try? await Task.sleep(for: .seconds(SmartOpening.clipboardWindow))
            guard !Task.isCancelled else { return }
            self?.highlighted = nil
        }
    }

    func start() {
        guard timer == nil else { return }
        self.timer = RepeatingTimer.start(every: 0.75) { [weak self] in self?.poll() }
    }

    private func poll() {
        // The same tick notes copies for the smart opening (spec SO-2).
        ClipboardWatcher.shared.poll()
        let board = NSPasteboard.general
        guard board.changeCount != lastCount else { return }
        lastCount = board.changeCount
        let types = board.types?.map(\.rawValue) ?? []
        guard !ClipboardRules.isSkipped(types: types),
              !excludedApps.contains(NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "")
        else { return }
        if let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
           board.types?.contains(.fileURL) != true {
            history = ClipboardRules.adding(ClipItem(kind: .text, text: text), to: history, limit: limit)
        } else if let image = NSImage(pasteboard: board), let item = storeImage(image) {
            // E.g. a screenshot tool's capture (spec CB-5).
            history = ClipboardRules.adding(item, to: history, limit: limit)
        } else {
            return
        }
        removeUnusedImages()
        persist()
    }

    private func storeImage(_ image: NSImage) -> ClipItem? {
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff),
              let png = bitmap.representation(using: .png, properties: [:]), png.count < 20_000_000
        else { return nil }
        let name = UUID().uuidString + ".png"
        try? FileManager.default.createDirectory(at: imagesFolder, withIntermediateDirectories: true)
        guard (try? png.write(to: imagesFolder.appendingPathComponent(name))) != nil else { return nil }
        return ClipItem(kind: .image, text: "Image \(bitmap.pixelsWide)×\(bitmap.pixelsHigh)", imageFile: name)
    }

    func image(of item: ClipItem) -> NSImage? {
        item.imageFile.flatMap { NSImage(contentsOf: imagesFolder.appendingPathComponent($0)) }
    }

    // MARK: - Pasting (spec CB-3)

    /// Puts the item on the pasteboard and pastes it into the app in front with ⌘V.
    func paste(_ item: ClipItem) {
        copy(item)
        Self.pressCommandV()
    }

    /// Puts the item on the pasteboard; it comes first in the history again (spec PV-22).
    func copy(_ item: ClipItem) {
        let board = NSPasteboard.general
        board.clearContents()
        if item.kind == .image, let image = image(of: item) {
            board.writeObjects([image])
        } else {
            board.setString(item.text, forType: .string)
        }
        lastCount = board.changeCount
        // The pasted copy comes first again, as in Flycut.
        if history.contains(where: { $0.id == item.id }) {
            history = [item] + history.filter { $0.id != item.id }
            persist()
        }
    }

    private static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for isDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: isDown)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }

    // MARK: - Editing (spec CB-4)

    func toggleSaved(_ item: ClipItem) {
        if let index = saved.firstIndex(where: { $0.id == item.id || ($0.kind == .text && $0.text == item.text && item.kind == .text) }) {
            saved.remove(at: index)
        } else {
            saved.insert(item, at: 0)
        }
        persist()
    }

    func isSaved(_ item: ClipItem) -> Bool {
        saved.contains { $0.id == item.id || ($0.kind == .text && item.kind == .text && $0.text == item.text) }
    }

    /// Moves a saved item to `index`, as it is dragged (spec CB-8).
    func moveSaved(_ id: ClipItem.ID, to index: Int) {
        guard let from = saved.firstIndex(where: { $0.id == id }) else { return }
        let target = min(max(index, 0), saved.count - 1)
        guard target != from else { return }
        saved.insert(saved.remove(at: from), at: target)
        persist()
    }

    func addSaved(text: String) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        saved.insert(ClipItem(kind: .text, text: trimmed), at: 0)
        persist()
    }

    func remove(_ item: ClipItem, from tab: ClipboardTab) {
        if tab == .history { history.removeAll { $0.id == item.id } } else { saved.removeAll { $0.id == item.id } }
        removeUnusedImages()
        persist()
    }

    func clearHistory() {
        history = []
        removeUnusedImages()
        persist()
    }

    func setExcluded(_ identifier: String, _ excluded: Bool) {
        excludedApps.removeAll { $0 == identifier }
        if excluded { excludedApps.append(identifier) }
    }

    // MARK: - Disk

    private struct Saved: Codable {
        var history: [ClipItem]
        var saved: [ClipItem]
    }

    private var file: URL { folder.appendingPathComponent("items.json") }
    private var imagesFolder: URL { folder.appendingPathComponent("images") }

    private func load() {
        guard let data = try? Data(contentsOf: file), let stored = try? JSONDecoder().decode(Saved.self, from: data) else { return }
        history = Array(stored.history.prefix(limit))
        saved = stored.saved
    }

    private func persist() {
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        guard let data = try? JSONEncoder().encode(Saved(history: history, saved: saved)) else { return }
        try? data.write(to: file, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
    }

    private func removeUnusedImages() {
        let used = Set((history + saved).compactMap(\.imageFile))
        let files = (try? FileManager.default.contentsOfDirectory(atPath: imagesFolder.path)) ?? []
        for name in files where !used.contains(name) {
            try? FileManager.default.removeItem(at: imagesFolder.appendingPathComponent(name))
        }
    }
}

extension KeyShortcut {
    /// ⌥V: the clipboard history (spec CB-2).
    static let optionV = KeyShortcut(keyCode: 9, modifiers: 0x0800, display: "⌥V")
    /// ⌥⇧V: the saved items (spec CB-2).
    static let optionShiftV = KeyShortcut(keyCode: 9, modifiers: 0x0800 | 0x0200, display: "⌥⇧V")
}
